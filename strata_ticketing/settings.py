# SQLite WAL mode and busy timeout hook for maximum concurrency safety
from django.db.backends.signals import connection_created
from django.dispatch import receiver

@receiver(connection_created)
def configure_sqlite_concurrency(sender, connection, **kwargs):
    """
    Enables Write-Ahead Logging (WAL) and sets a 30s busy timeout
    to ensure smooth concurrent requests on SQLite without locking errors.
    """
    if connection.vendor == 'sqlite':
        cursor = connection.cursor()
        cursor.execute('PRAGMA journal_mode=WAL;')
        cursor.execute('PRAGMA busy_timeout=30000;')
        cursor.execute('PRAGMA synchronous=NORMAL;')

